function renderSpriteToCanvas(spriteName, paletteName, flipX = false, scale = 1) {
    const data = SPRITE_DATA[spriteName];
    const palette = PALETTES[paletteName];

    const height = data.length;
    const width = data[0].length;

    const canvas = document.createElement('canvas');
    canvas.width = Math.ceil(width * scale);
    canvas.height = Math.ceil(height * scale);
    const ctx = canvas.getContext('2d');

    if (flipX) {
        ctx.translate(canvas.width, 0);
        ctx.scale(-1, 1);
    }

    for (let y = 0; y < height; y++) {
        for (let x = 0; x < width; x++) {
            const colorIndex = parseInt(data[y][x]) - 1;
            const color = palette[colorIndex];
            if (color !== 'transparent') {
                ctx.fillStyle = color;
                const drawX = Math.floor(x * scale);
                const drawY = Math.floor(y * scale);
                const drawWidth = Math.ceil((x + 1) * scale) - drawX;
                const drawHeight = Math.ceil((y + 1) * scale) - drawY;
                ctx.fillRect(drawX, drawY, drawWidth, drawHeight);
            }
        }
    }
    return canvas;
}

